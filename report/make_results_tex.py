#!/usr/bin/env python3
"""Regenerate report/results.tex (number macros plus the per-type table rows) from the evaluation outputs.

Every number in the report comes from this script, so a re-run on a larger question set only
needs:  python report/make_results_tex.py
"""
from __future__ import annotations

import json
import math
import re
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
base = json.loads((ROOT / "outputs/qwen_base/qwen_base/result.json").read_text(encoding="utf-8"))
sft = json.loads((ROOT / "outputs/qwen_sft/qwen_sft/result.json").read_text(encoding="utf-8"))
vila = [json.loads(line) for line in (ROOT / "outputs/vila_reva_v2/outputs.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
vila_by_id = {r["qa_id"]: r for r in vila}
assert set(base) == set(sft) == set(vila_by_id), "the three models were not scored on the same question set"
n = len(base)

def pct(x: float) -> str:
    return f"{100 * x:.1f}"

macros: dict[str, str] = {"NQ": str(n)}
for tag, correct, answered in (
    ("Base", sum(v["acc"] for v in base.values()), sum(bool(v["pred_letter"]) for v in base.values())),
    ("Sft", sum(v["acc"] for v in sft.values()), sum(bool(v["pred_letter"]) for v in sft.values())),
    ("Vila", sum(bool(r["is_correct"]) for r in vila), sum(r["pred_letter"] not in (None, "") for r in vila)),
):
    macros[f"Cor{tag}"], macros[f"Ans{tag}"], macros[f"Acc{tag}"] = str(correct), str(answered), pct(correct / n)

gain = [k for k in base if not base[k]["acc"] and sft[k]["acc"]]
loss = [k for k in base if base[k]["acc"] and not sft[k]["acc"]]
disc, small = len(gain) + len(loss), min(len(gain), len(loss))
p_value = min(1.0, 2 * sum(math.comb(disc, i) for i in range(small + 1)) / 2**disc)
macros.update({
    "Gain": str(len(gain)), "Loss": str(len(loss)), "NetGain": str(len(gain) - len(loss)),
    "BothRight": str(sum(1 for k in base if base[k]["acc"] and sft[k]["acc"])),
    "BothWrong": str(sum(1 for k in base if not base[k]["acc"] and not sft[k]["acc"])),
    "McNemarP": f"{p_value:.3f}",
    "StdErr": pct(math.sqrt(0.65 * 0.35 / n)),
    "MedLenBase": str(int(statistics.median(len(v["pred"]) for v in base.values()))),
    "MedLenSft": str(int(statistics.median(len(v["pred"]) for v in sft.values()))),
    "DirectBase": str(sum(v["pred"].lstrip().startswith("<answer>") for v in base.values())),
    "DirectSft": str(sum(v["pred"].lstrip().startswith("<answer>") for v in sft.values())),
    "LossPickedC": str(sum(1 for k in loss if sft[k]["pred_letter"] == "C")),
})
for tag, letters in (
    ("Gt", Counter(v["gt"] for v in base.values())),
    ("Base", Counter(v["pred_letter"] for v in base.values())),
    ("Sft", Counter(v["pred_letter"] for v in sft.values())),
    ("Vila", Counter(r["pred_letter"] for r in vila)),
):
    for letter in "ABCD":
        macros[f"Let{tag}{letter}"] = str(letters.get(letter, 0))

macros["AllRight"] = str(sum(1 for k in base if base[k]["acc"] and sft[k]["acc"] and vila_by_id[k]["is_correct"]))
macros["AllWrong"] = str(sum(1 for k in base if not base[k]["acc"] and not sft[k]["acc"] and not vila_by_id[k]["is_correct"]))

# Timestamp check on Temporal Grounding: times that the baseline states in its own reasoning and
# that are not option values. The inference script labels the frames 0.2 s and 1.1 s (see the report),
# so a baseline that reasons on those labels only mentions times of at most 1.4 s.
gt_file = ROOT / "reva_eval/data/rsvidqa/reva_v2_test_set.json"
questions = {g["id"]: g["question"] for g in json.loads(gt_file.read_text(encoding="utf-8"))}
tg = [k for k in base if base[k]["question_type"] == "Temporal Grounding"]
short = []
for k in tg:
    reasoning = base[k]["pred"].split("<answer>")[0]
    stated = [float(x) for x in re.findall(r"(?<![\d.])(\d+\.\d+)\s*(?:s\b|seconds?)", reasoning)]
    option_values = {float(x) for x in re.findall(r"(\d+\.\d+)", questions.get(k, ""))}
    own = [t for t in stated if t not in option_values]
    if own and max(own) <= 1.4:
        short.append(k)
macros.update({"TGTotal": str(len(tg)), "TGShortTime": str(len(short)),
               "TGShortTimeCorrect": str(sum(base[k]["acc"] for k in short))})

# Training curve: the Hugging Face Trainer stores one log entry per optimizer step.
history = json.loads((ROOT / "outputs/qwen_reva_sft/trainer_state.json").read_text(encoding="utf-8"))["log_history"]
losses = [entry["loss"] for entry in history if "loss" in entry]
runtime = next(entry["train_runtime"] for entry in history if "train_runtime" in entry)
macros.update({"TrainSteps": str(len(losses)), "LossFirstTen": f"{sum(losses[:10]) / 10:.2f}",
               "LossLastTen": f"{sum(losses[-10:]) / 10:.2f}", "TrainSeconds": f"{runtime:.0f}"})

lines = ["% Auto-generated by report/make_results_tex.py. Do not edit by hand."]
lines += ["\\newcommand{\\" + name + "}{" + value + "}" for name, value in macros.items()]
(ROOT / "report/results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

types = sorted({v["question_type"] for v in base.values()})
g, l = Counter(base[k]["question_type"] for k in gain), Counter(base[k]["question_type"] for k in loss)
rows = []
for t in types:
    ids = [k for k in base if base[k]["question_type"] == t]
    b, s, v = (sum(base[k]["acc"] for k in ids), sum(sft[k]["acc"] for k in ids), sum(bool(vila_by_id[k]["is_correct"]) for k in ids))
    rows.append(f"{t} & {len(ids)} & {pct(b / len(ids))} & {pct(s / len(ids))} & {pct(v / len(ids))} & +{g[t]} / $-${l[t]} \\\\")
# The rows go into a macro (not a separate \input file): \input directly before \bottomrule
# inside a tabular raises "Misplaced \noalign".
with (ROOT / "report/results.tex").open("a", encoding="utf-8") as f:
    f.write("\\newcommand{\\TypeRows}{%\n" + "\n".join(rows) + "\n}\n")
print(f"wrote {len(macros)} macros and {len(rows)} table rows for n = {n}")
